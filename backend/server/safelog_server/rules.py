"""
The reward ledger — line-for-line the same rules as android/core/.../ledger/Ledger.kt.
Golden cases: backend/contract/ledger_cases.json (generated by the Kotlin side, replayed by tests/test_ledger_cases.py).

Driver state is stored in the same JSON schema as the car (Codec.driver in Persistence.kt).
"""
from __future__ import annotations

import math
from datetime import date, datetime, timedelta
from zoneinfo import ZoneInfo

from .catalog import GRADES, MISSIONS, MISSION_BY_HABIT, MIN_OPPS_TO_REPORT, QUIZ, R, SHOP, label, mission_passed, tier, weight

ZONE = ZoneInfo("Asia/Seoul")
EPOCH = date(1970, 1, 1)


def today(ms: int) -> date:
    return datetime.fromtimestamp(ms / 1000, ZONE).date()


def week_start(d: date) -> date:
    return d - timedelta(days=d.weekday())


def ym(d: date) -> tuple[int, int]:
    return d.year, d.month


def add_months(y_m: tuple[int, int], n: int) -> tuple[int, int]:
    y, m = y_m
    k = y * 12 + (m - 1) + n
    return k // 12, k % 12 + 1


def months_between(a: tuple[int, int], b: tuple[int, int]) -> int:
    return (b[0] * 12 + b[1]) - (a[0] * 12 + a[1])


def round_half_up(x: float) -> int:
    """Kotlin roundToInt() = Math.round = floor(x + 0.5)."""
    return int(math.floor(x + 0.5))


def cost(price: int, grade: dict) -> int:
    return price * (100 - grade["discount"]) // 100


def grade_of(km: float) -> dict:
    return [g for g in GRADES if km >= g["fromKm"]][-1]


def xp_for_level(level: int) -> int:
    if level <= 1:
        return 0
    if level <= 4:
        return (level - 1) * 100
    if level <= 10:
        return 500 + (level - 5) * 200
    return 1500 + (level - 10) * 300


def level_for(total: int) -> int:
    lv = 1
    while xp_for_level(lv + 1) <= total:
        lv += 1
    return lv


def level_progress(total: int) -> tuple[int, int]:
    lv = level_for(total)
    return total - xp_for_level(lv), xp_for_level(lv + 1) - xp_for_level(lv)


def xp_to_next(total: int) -> int:
    return xp_for_level(level_for(total) + 1) - total


def capped(earned_month: int, amount: int) -> int:
    return max(0, min(amount, R["monthlyCap"] - earned_month))


def new_driver(did: str, name: str, mode: str = "Training") -> dict:
    return {"id": did, "name": name, "mode": mode, "first_trip_ms": None, "xp_total": 0, "atlas_name": "아틀라스", "voice": "basic",
            "entries": [], "trips": [], "profile": {"trips": 0, "habits": {}}, "mission_clears": {}, "insurance": None, "quiz": None,
            "recommended": None, "exchanges": {}, "last_tags": [], "cleared_before_ms": 0,
            "mode_notice": None, "training_streak": 0, "graduated": False, "avatar": "atlas", "tour_rewarded": False}


def recent_score(scores: list[int]) -> float:
    """장기 점수 = 최근 5회 가중 평균: weights 1..5 from the oldest to the newest trip (Rules.recentScore)."""
    last = scores[-R["scoreWindow"]:]
    if not last:
        return 100.0
    num = sum((k + 1) * x for k, x in enumerate(last))
    return num / sum(k + 1 for k in range(len(last)))


def set_mode(d: dict, mode: str) -> None:
    """The driver's own switch (SafeLogCore.setTrainingMode): no notice, the streak starts over."""
    d["mode"] = mode
    d["training_streak"] = 0


def tour_complete(d: dict, metrics: dict | None = None) -> bool:
    """S05 내 차 익히기 finished: +50 XP once per driver. Returns True if it was granted now.

    [metrics] (practice time, steps, skipped steps) come only from drivers who turned 데이터 기여 on; kept once."""
    if metrics and "tour_metrics" not in d:
        d["tour_metrics"] = metrics
    if d.get("tour_rewarded"):
        return False
    d["tour_rewarded"] = True
    d["xp_total"] += R["tourXp"]
    return True


MAX_CONTRIBUTED_TRIPS = 200


def add_metrics(d: dict, trip_id: str, metrics: list[dict]) -> None:
    """Summary indicators of one trip for the data-contribution programme (no raw signals). The car sends them only
    when the driver opted in; the newest [MAX_CONTRIBUTED_TRIPS] trips are kept."""
    kept = [x for x in d.get("contributed", []) if x["tripId"] != trip_id]
    kept.append({"tripId": trip_id, "metrics": metrics})
    d["contributed"] = kept[-MAX_CONTRIBUTED_TRIPS:]


def add_dispute(d: dict, trip_id: str, scene_id: str, what: str, good: bool, ms: int) -> bool:
    """오판정 의견: the driver marked a journal scene as judged wrong. One mark per scene; True if it is new."""
    disputes = d.setdefault("disputes", [])
    if any(x["sceneId"] == scene_id for x in disputes):
        return False
    disputes.append({"tripId": trip_id, "sceneId": scene_id, "what": what, "good": good, "ms": ms})
    for t in d["trips"]:
        if t["id"] == trip_id:
            for s in t.get("scenes", []):
                if s.get("id") == scene_id:
                    s["disputed"] = True
    return True


def balance(d: dict) -> int:
    return sum(e["points"] for e in d["entries"])


def earned_in_month(d: dict, y_m) -> int:
    return sum(e["points"] for e in d["entries"] if e["points"] > 0 and ym(today(e["ms"])) == y_m)


def trip_date(t: dict) -> date:
    return today(t["start_ms"])


def safe_mileage(d: dict, now_ms: int) -> float:
    n = today(now_ms)
    try:
        frm = n.replace(year=n.year - 1)
    except ValueError:                       # 29 Feb
        frm = n.replace(year=n.year - 1, day=28)
    return sum(t["safe_km"] for t in d["trips"] if not trip_date(t) < frm)


def week_streak(d: dict, day: date, include_current: bool, extra_day: date | None = None) -> int:
    days = {trip_date(t) for t in d["trips"] if t["attended"]}
    if extra_day:
        days.add(extra_day)

    def full(wk):
        return sum(1 for x in days if week_start(x) == wk) >= R["weekDays"]
    wk = week_start(day)
    if not full(wk):
        if include_current:
            return 0
        wk -= timedelta(weeks=1)
    n = 0
    while full(wk):
        n += 1
        wk -= timedelta(weeks=1)
    return n


def good_habits(counts: dict) -> list[list]:
    items = [(h, c) for h, c in counts.items() if c[0] > 0 and (tier(h) == "X" or c[1] >= MIN_OPPS_TO_REPORT)]
    items.sort(key=lambda kv: -weight(kv[0]) * kv[1][0])          # stable, like Kotlin sortedBy
    return [[label(h), c[0], c[0] if tier(h) == "X" else c[1]] for h, c in items]


def new_insurance(now_ms: int) -> dict:
    y, m = add_months(ym(today(now_ms)), 12)
    return {"safe_km": 0.0, "goal_km": R["insuranceGoalKm"], "renewal": f"{y:04d}-{m:02d}", "max_discount": R["insuranceMaxDiscount"]}


def insurance_view(d: dict, now_ms: int) -> dict | None:
    ins = d.get("insurance")
    if not ins:
        return None
    ry, rm = (int(x) for x in ins["renewal"].split("-"))
    recent = [t for t in d["trips"][-10:] if t["km"] > 0.5]
    avg = 30 if not recent else max(1, round_half_up(sum(t["km"] for t in recent) / len(recent)))
    return {"safeKm": int(ins["safe_km"]), "goalKm": ins["goal_km"], "renewal": f"{ry}년 {rm}월",
            "monthsToRenewal": max(0, months_between(ym(today(now_ms)), (ry, rm))), "avgTripKm": avg,
            "maxDiscountPercent": ins["max_discount"]}


def next_reward(d: dict, now_ms: int, shop=SHOP) -> dict:
    g = grade_of(safe_mileage(d, now_ms))
    bal = balance(d)
    items = sorted(((it, cost(it["price"], g)) for it in shop if it["category"] != "Atlas"), key=lambda x: x[1])
    target = next((x for x in items if x[1] > bal), items[-1] if items else None)
    if target is None:
        return {"itemName": "교환소", "remainingPoints": 0, "price": 1, "art": "", "image": None}
    return {"itemName": target[0]["name"], "remainingPoints": max(0, target[1] - bal), "price": target[1], "art": target[0]["art"],
            "image": target[0].get("image")}


def settle(d: dict, f: dict, insurance_share: bool, now_ms: int | None = None) -> dict:
    """POST /drives/{id}/finish. Returns {"arrival": ..., "breakdown": ..., "log": ...}; mutates the driver."""
    now_ms = f["endMs"] if now_ms is None else now_ms
    day = today(f["startMs"])
    month = ym(day)
    breakdown: dict[str, int] = {}
    if d["first_trip_ms"] is None and f.get("identified", True):
        d["first_trip_ms"] = f["startMs"]

    def earn(kind, amount):
        if amount <= 0:
            return
        got = capped(earned_in_month(d, month), amount)
        if got > 0:
            d["entries"].append({"id": f"{f['id']}:{kind}", "ms": f["endMs"], "kind": kind, "points": got, "ref": f["id"]})
            breakdown[kind] = breakdown.get(kind, 0) + got

    counts = {h: list(c) for h, c in f["counts"].items()}
    results = []
    for m in f["missions"]:
        mm = MISSIONS.get(m["id"])
        if mm:
            results.append((mm, m["recommended"], counts.get(mm["habit"], [0, 0])))
    cleared = [r for r in results if mission_passed(r[0], r[2][0], r[2][1])]
    identified = f.get("identified", True)
    earns = identified and not f["blocked"]
    attended = False
    if earns:
        already = any(t["attended"] and trip_date(t) == day for t in d["trips"])
        if not already:
            attended = True
            first_month = (day - today(d["first_trip_ms"])).days < R["firstMonthDays"]
            earn("attendance", R["attendFirstMonth"] if first_month else R["attendLater"])
            wk = week_start(day)
            days_before = len({trip_date(t) for t in d["trips"] if t["attended"] and week_start(trip_date(t)) == wk})
            if days_before + 1 == R["weekDays"]:
                earn("week", R["weekBonus"])
                streak = week_streak(d, day, True, day)
                if streak == 4:
                    earn("streak4", R["streak4"])
                if streak >= 8 and streak % 4 == 0:
                    earn("streak8", R["streak8"])
        for mm, rec, _c in cleared:
            earn(f"mission:{mm['id']}", mm["points"] * 2 if rec else mm["points"])
            n = d["mission_clears"].get(mm["id"], 0) + 1
            d["mission_clears"][mm["id"]] = n
            if n % R["stampEvery"] == 0:
                earn(f"stamp:{mm['id']}", R["stampBonus"])
    # ③ 연수 모드 (same rules as Ledger.settle): a weak score only SUGGESTS it ("TrainingOffer", the driver turns it on
    #    with PUT /mode); three missions passed in a row with a good average graduate back to 평소 모드
    mode_before = d["mode"]
    graduation = False
    score = f.get("score", 100)
    if identified:
        avg = recent_score([t["score"] for t in d["trips"] if t.get("score", -1) >= 0] + [score])
        if d["mode"] != "Training":
            if avg < R["trainingOnAvg"] or score < R["trainingOnTrip"]:
                d["mode_notice"] = "TrainingOffer"
        else:
            if f["blocked"]:
                d["training_streak"] = 0
            elif results:
                d["training_streak"] = d.get("training_streak", 0) + 1 if len(cleared) == len(results) else 0
            if d["training_streak"] >= R["trainingOffStreak"] and avg >= R["trainingOffAvg"]:
                d["mode"], d["mode_notice"], d["training_streak"] = "Normal", "TrainingOff", 0
                if earns and not d.get("graduated"):
                    d["graduated"] = True
                    graduation = True
                    earn("graduation", R["graduationPoints"])
    points = sum(breakdown.values())
    mission_xp = sum(R["missionXp"] * 2 if rec else R["missionXp"] for _m, rec, _c in cleared)
    xp = f["tierXp"] + mission_xp + (R["graduationXp"] if graduation else 0) if earns else 0
    d["xp_total"] += xp
    safe_km = f["km"] if identified and not f["blocked"] and not f["riskMoment"] else 0.0
    if insurance_share and identified:
        if not d.get("insurance"):
            d["insurance"] = new_insurance(now_ms)
        d["insurance"]["safe_km"] += safe_km
    log = {"id": f["id"], "start_ms": f["startMs"], "end_ms": f["endMs"], "km": f["km"], "safe_km": safe_km, "blocked": f["blocked"],
           "counts": counts, "missions": [m["id"] for m in f["missions"]], "cleared": [m[0]["id"] for m in cleared],
           "scenes": f.get("scenes", []), "summary": f.get("summary", ""), "points": points, "xp": xp, "attended": attended,
           "score": score if identified else -1, "mode": mode_before}
    d["trips"].append(log)
    d["last_tags"] = sorted(f.get("tags", []))
    good = good_habits(counts)
    first = results[0] if results else None
    not_cleared = [r for r in results if r not in cleared]
    if not_cleared:
        nxt = not_cleared[0][0]["title"]
    elif f.get("weakestHabit") and f["weakestHabit"] in MISSION_BY_HABIT:
        nxt = MISSION_BY_HABIT[f["weakestHabit"]]["title"]
    else:
        nxt = None
    gh = lambda x: {"label": x[0], "success": x[1], "chances": x[2]}
    arrival = {
        "topHabit": gh(good[0]) if good else None,
        "otherHabits": [gh(x) for x in good[1:4]],
        "points": points, "xp": xp, "xpToNextLevel": xp_to_next(d["xp_total"]),
        "nextReward": next_reward(d, now_ms),
        "practiceResult": {"label": first[0]["title"], "success": first[2][0], "chances": first[2][1]} if first else None,
        "nextChallenge": nxt,
        "practiceCleared": bool(first and any(c[0]["id"] == first[0]["id"] for c in cleared)),
        "practicePoints": sum(breakdown.get(f"mission:{m['id']}", 0) for m, _r, _c in cleared),
        "noRewardReason": "운전자를 고르면 다음부터 쌓여요" if not identified else ("다음 주행에서 다시 모아 봐요" if f["blocked"] else None),
        "insurance": insurance_view(d, now_ms) if insurance_share else None,
        "safeKmToday": round_half_up(safe_km),
    }
    return {"arrival": arrival, "breakdown": breakdown, "log": log}


def quiz_of(d: dict, now_ms: int) -> dict:
    day = today(now_ms)
    st = d.get("quiz")
    if not st or st["date"] != day.isoformat():
        tags = set(d.get("last_tags", []))
        related = [q for q in QUIZ if any(t in tags for t in q["tags"])] or QUIZ
        q = related[(day - EPOCH).days % len(related)]
        st = {"date": day.isoformat(), "id": q["id"], "picked": None}
        d["quiz"] = st
    return st


def answer_quiz(d: dict, choice: int, now_ms: int) -> int:
    st = quiz_of(d, now_ms)
    if st["picked"] is not None:
        return 0
    st["picked"] = choice
    q = next(x for x in QUIZ if x["id"] == st["id"])
    amount = R["quizRight"] if choice == q["answer"] else R["quizWrong"]
    got = capped(earned_in_month(d, ym(today(now_ms))), amount)
    if got > 0:
        d["entries"].append({"id": f"quiz:{st['date']}", "ms": now_ms, "kind": "quiz", "points": got, "ref": st["id"]})
    return got


def exchange(d: dict, item: dict, request_id: str, now_ms: int) -> str:
    if request_id in d["exchanges"]:
        return d["exchanges"][request_id]
    c = cost(item["price"], grade_of(safe_mileage(d, now_ms)))
    if balance(d) < c:
        r = "NOT_ENOUGH_POINTS"
    else:
        d["entries"].append({"id": f"exchange:{request_id}", "ms": now_ms, "kind": "exchange", "points": -c, "ref": item["id"]})
        r = "OK"
    d["exchanges"][request_id] = r
    return r
